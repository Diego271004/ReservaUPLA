export const porClave = (clave) => {
  const c = CODIGOS.find((x) => x.clave === clave)
  if (!c) throw new Error(`Fragmento de código desconocido: ${clave}`)
  return c
}

/** Localiza el rango real (líneas 1-based) de un fragmento en el repositorio. */
export function rangoDe(codigo, lineas) {
  const i = lineas.findIndex((l) => l.includes(codigo.ancla))
  if (i < 0) throw new Error(`Ancla no encontrada en ${codigo.ruta}: ${codigo.ancla}`)
  const ini = Math.max(0, i - codigo.antes)
  const fin = Math.min(lineas.length, ini + codigo.n + codigo.antes)
  return { ini: ini + 1, fin }
}
